import { useStudy, PROGRESS_LABELS, PROGRESS_COLORS } from '../context/StudyContext'
import { useQuran } from '../context/QuranContext'

function buildProgressText(verses, surahNo, getVerseProgress) {
  const lines = [`Memorization Progress — ${verses[0]?.surahName || 'Surah'}\n`]
  const counts = { memorized: 0, learning: 0, 'not-started': 0 }
  verses.forEach((v) => {
    const p = getVerseProgress(surahNo, v.ayahNo)
    counts[p]++
    lines.push(`Verse ${v.ayahNo}: ${PROGRESS_LABELS[p]}`)
  })
  lines.push(`\nSummary: ${counts.memorized} memorized · ${counts.learning} learning · ${counts['not-started']} not started`)
  return lines.join('\n')
}

export default function ExportModal({ onClose }) {
  const { verses, selectedSurah } = useQuran()
  const { getVerseProgress, notes } = useStudy()

  const handleCopyText = () => {
    const text = buildProgressText(verses, selectedSurah.number, getVerseProgress)
    navigator.clipboard.writeText(text).then(() => alert('Copied to clipboard!'))
  }

  const handleShare = async () => {
    const text = buildProgressText(verses, selectedSurah.number, getVerseProgress)
    if (navigator.share) {
      await navigator.share({ title: `Quran Progress — ${selectedSurah.name}`, text })
    } else {
      navigator.clipboard.writeText(text).then(() => alert('Copied to clipboard (Web Share not supported)'))
    }
  }

  const handlePDF = () => {
    // Build a printable HTML page and open in new tab
    const noteEntries = Object.entries(notes)
      .filter(([k]) => k.startsWith(`${selectedSurah.number}:`))
      .map(([k, v]) => `<li><b>Verse ${k.split(':')[1]}:</b> ${v}</li>`)
      .join('')

    const counts = { memorized: 0, learning: 0, 'not-started': 0 }
    verses.forEach((v) => counts[getVerseProgress(selectedSurah.number, v.ayahNo)]++)

    const rows = verses.map((v) => {
      const p = getVerseProgress(selectedSurah.number, v.ayahNo)
      return `<tr>
        <td style="text-align:center">${v.ayahNo}</td>
        <td style="color:${PROGRESS_COLORS[p]};font-weight:600">${PROGRESS_LABELS[p]}</td>
        <td style="font-size:11px;color:#555">${notes[`${selectedSurah.number}:${v.ayahNo}`] || ''}</td>
      </tr>`
    }).join('')

    const html = `<!DOCTYPE html><html><head><meta charset="utf-8">
    <title>Quran Progress — ${selectedSurah.name}</title>
    <style>
      body{font-family:Arial,sans-serif;padding:32px;color:#1a1a2e}
      h1{color:#0f3d22;margin-bottom:4px}
      h2{color:#5a7a6a;font-weight:400;margin-bottom:24px;font-size:15px}
      .summary{display:flex;gap:24px;margin-bottom:24px;padding:16px;background:#f5f5f0;border-radius:8px}
      .summary span{font-weight:600}
      table{width:100%;border-collapse:collapse}
      th{background:#0f3d22;color:#fff;padding:8px 12px;text-align:left;font-size:13px}
      td{padding:8px 12px;border-bottom:1px solid #eee;font-size:13px;vertical-align:top}
      tr:nth-child(even) td{background:#fafaf8}
      .notes-section{margin-top:32px}
      .notes-section h3{color:#0f3d22;margin-bottom:12px}
      ul{padding-left:20px;line-height:1.8;font-size:13px}
      @media print{body{padding:16px}}
    </style></head><body>
    <h1>📖 ${selectedSurah.number}. ${selectedSurah.name}</h1>
    <h2>${selectedSurah.englishName} — Memorization Progress Report</h2>
    <div class="summary">
      <span style="color:#2e8b57">● ${counts.memorized} Memorized</span>
      <span style="color:#e8a020">◑ ${counts.learning} Learning</span>
      <span style="color:#aaa">○ ${counts['not-started']} Not Started</span>
      <span style="color:#555">Total: ${verses.length} verses</span>
    </div>
    <table>
      <thead><tr><th style="width:60px">Verse</th><th style="width:160px">Status</th><th>Notes</th></tr></thead>
      <tbody>${rows}</tbody>
    </table>
    ${noteEntries ? `<div class="notes-section"><h3>📝 Notes</h3><ul>${noteEntries}</ul></div>` : ''}
    <p style="margin-top:32px;font-size:11px;color:#aaa">Generated by Quran Memorization App · ${new Date().toLocaleDateString()}</p>
    </body></html>`

    const win = window.open('', '_blank')
    win.document.write(html)
    win.document.close()
    setTimeout(() => win.print(), 500)
  }

  const memorized = verses.filter((v) => getVerseProgress(selectedSurah.number, v.ayahNo) === 'memorized').length
  const learning = verses.filter((v) => getVerseProgress(selectedSurah.number, v.ayahNo) === 'learning').length
  const pct = verses.length ? Math.round((memorized / verses.length) * 100) : 0

  return (
    <div className="export-overlay" onClick={(e) => e.target === e.currentTarget && onClose()}>
      <div className="export-modal" role="dialog" aria-modal="true" aria-label="Export progress">
        <div className="export-header">
          <span>Export Progress — {selectedSurah.name}</span>
          <button onClick={onClose} aria-label="Close export">✕</button>
        </div>

        <div className="export-summary">
          <div className="export-stat" style={{ '--c': PROGRESS_COLORS.memorized }}>
            <span className="export-stat-num">{memorized}</span>
            <span className="export-stat-label">Memorized</span>
          </div>
          <div className="export-stat" style={{ '--c': PROGRESS_COLORS.learning }}>
            <span className="export-stat-num">{learning}</span>
            <span className="export-stat-label">Learning</span>
          </div>
          <div className="export-stat" style={{ '--c': '#aaa' }}>
            <span className="export-stat-num">{verses.length - memorized - learning}</span>
            <span className="export-stat-label">Not Started</span>
          </div>
          <div className="export-stat" style={{ '--c': '#0f3d22' }}>
            <span className="export-stat-num">{pct}%</span>
            <span className="export-stat-label">Complete</span>
          </div>
        </div>

        <div className="export-progress-bar">
          <div className="export-progress-fill" style={{ width: pct + '%' }} />
        </div>

        <div className="export-actions">
          <button className="export-btn primary" onClick={handlePDF}>🖨️ Print / Save PDF</button>
          <button className="export-btn" onClick={handleShare}>📤 Share</button>
          <button className="export-btn" onClick={handleCopyText}>📋 Copy Text</button>
        </div>
      </div>
    </div>
  )
}
